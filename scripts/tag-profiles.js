// Suggests skills for every employee profile using a local LLM (Ollama).
// Only skills that already exist in the database can be assigned.
// Writes to the existing employee_skills table; no schema changes needed.
//
// Setup (once):  install Ollama, then  ollama pull qwen2.5:3b
// Run (needs Node 20.6+ and DATABASE_URL in .env.local, see CLAUDE.md):
//   node --env-file=.env.local scripts/tag-profiles.js           -> writes db/profile-tags.sql only (review it)
//   node --env-file=.env.local scripts/tag-profiles.js --apply   -> also replaces each person's skills in the database
// Run it after adding or changing profiles.

import { writeFileSync } from "node:fs";
import { neon } from "@neondatabase/serverless";

const OLLAMA_URL = process.env.OLLAMA_URL || "http://localhost:11434";
const MODEL = process.env.OLLAMA_MODEL || "qwen2.5:3b";
const MIN_CONFIDENCE = 0.5;   // tags below this are dropped
const MAX_SKILLS = 5;
const APPLY = process.argv.includes("--apply");
const OUT_FILE = new URL("../db/profile-tags.sql", import.meta.url);

const sql = neon(process.env.DATABASE_URL);

const SYSTEM = `You tag employee profiles for an internal expert-finding tool.
Only use the skills you are given, spelled exactly as listed.
Base every tag on evidence in the profile (job role, expertise, projects). Do not guess.`;

function prompt(p, skills) {
  return `Skills:
${skills.map((s) => "- " + s).join("\n")}

Profile:
Job role: ${p.job_role || "-"}
Expertise: ${p.expertise || "-"}
Projects: ${(p.projects || []).join("; ") || "-"}

Return "skills": the skills this person clearly has (at most ${MAX_SKILLS}), each with a confidence from 0 to 1.
Use an empty list when nothing fits.`;
}

function schema(skills) {
  return {
    type: "object",
    properties: {
      skills: {
        type: "array",
        items: {
          type: "object",
          properties: { name: { type: "string", enum: skills }, confidence: { type: "number" } },
          required: ["name", "confidence"],
        },
      },
    },
    required: ["skills"],
  };
}

async function askLLM(profile, skills) {
  const res = await fetch(`${OLLAMA_URL}/api/chat`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      model: MODEL,
      stream: false,
      format: schema(skills),
      options: { temperature: 0 },
      messages: [
        { role: "system", content: SYSTEM },
        { role: "user", content: prompt(profile, skills) },
      ],
    }),
  });
  if (!res.ok) throw new Error(`Ollama returned ${res.status}: ${await res.text()}`);
  const data = await res.json();
  return JSON.parse(data.message.content);
}

// Keep only known, confident, de-duplicated skills (the model can still slip).
function clean(out, skills) {
  const seen = new Set();
  return (out.skills || [])
    .filter((x) => skills.includes(x.name) && x.confidence >= MIN_CONFIDENCE && !seen.has(x.name) && seen.add(x.name))
    .sort((a, b) => b.confidence - a.confidence)
    .slice(0, MAX_SKILLS)
    .map((x) => x.name);
}

const lit = (v) => "'" + String(v).replace(/'/g, "''") + "'";

function snapshot(email, tags) {
  const lines = [
    `-- ${email}`,
    `DELETE FROM employee_skills WHERE employee_id = (SELECT id FROM employees WHERE email = ${lit(email)});`,
  ];
  if (tags.length) {
    lines.push(`INSERT INTO employee_skills (employee_id, skill_id) SELECT e.id, s.id FROM employees e, skills s WHERE e.email = ${lit(email)} AND s.name IN (${tags.map(lit).join(", ")}) ON CONFLICT DO NOTHING;`);
  }
  return lines.join("\n");
}

async function apply(email, tags) {
  if (!tags.length) return; // never wipe someone's skills because the model found none
  await sql.transaction([
    sql`DELETE FROM employee_skills WHERE employee_id = (SELECT id FROM employees WHERE email = ${email})`,
    sql`INSERT INTO employee_skills (employee_id, skill_id)
      SELECT e.id, s.id FROM employees e, skills s WHERE e.email = ${email} AND s.name = ANY(${tags}) ON CONFLICT DO NOTHING`,
  ]);
}

async function main() {
  const skills = (await sql`SELECT name FROM skills ORDER BY name`).map((r) => r.name);
  const profiles = await sql`
    SELECT email, full_name, job_role, expertise, COALESCE(projects, '{}') AS projects
    FROM employees WHERE email IS NOT NULL AND expertise IS NOT NULL ORDER BY full_name`;

  console.log(`Tagging ${profiles.length} profiles with ${MODEL} (${skills.length} skills)${APPLY ? ", applying to the database" : ""}`);
  const parts = [`-- Generated by scripts/tag-profiles.js with ${MODEL} on ${new Date().toISOString()}.`,
    "-- Review, then run in the Neon SQL Editor (or use --apply). Safe to run more than once.", ""];

  for (const p of profiles) {
    try {
      const tags = clean(await askLLM(p, skills), skills);
      if (tags.length) parts.push(snapshot(p.email, tags), "");
      if (APPLY) await apply(p.email, tags);
      console.log(`  ${p.full_name}: ${tags.join(", ") || "no skills found, left unchanged"}`);
    } catch (err) {
      console.error(`  ${p.full_name}: skipped (${err.message})`);
    }
  }

  writeFileSync(OUT_FILE, parts.join("\n"));
  console.log(`Wrote ${OUT_FILE.pathname}`);
}

main().catch((err) => { console.error(err.message); process.exit(1); });
